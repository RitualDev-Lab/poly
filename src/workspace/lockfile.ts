import fs from "node:fs";
import path from "node:path";
import type {
  CompositeLockfile,
  DriftIssue,
  DriftReport,
  Ecosystem,
  MemberLockSnapshot,
} from "../types.js";
import { resolveWorkspaceMembers } from "./config.js";
import { computeFileHash, extractDirectDependencies } from "./crypto.js";

const SCHEMA_VERSION = 1;
const HASH_ALGO = "sha256";

/**
 * Generates an in-memory composite snapshot of all workspace members.
 */
export function generateCompositeLockfile(workspaceDir: string): CompositeLockfile {
  const members = resolveWorkspaceMembers(workspaceDir);
  const snapshots: MemberLockSnapshot[] = [];

  for (const member of members) {
    const manifestPath = path.join(member.absoluteDir, member.context.manifestFile);
    const manifestHash = computeFileHash(manifestPath);

    let lockfileHash: string | undefined;
    if (member.context.lockfile) {
      const lockfilePath = path.join(member.absoluteDir, member.context.lockfile);
      lockfileHash = computeFileHash(lockfilePath);
    }

    const directDeps = extractDirectDependencies(manifestPath, member.context.ecosystem);

    snapshots.push({
      path: member.relativeDir,
      ecosystem: member.context.ecosystem,
      manifest: member.context.manifestFile,
      manifestHash,
      lockfile: member.context.lockfile,
      lockfileHash,
      directDependencies: directDeps,
    });
  }

  // Sort member paths deterministically
  snapshots.sort((a, b) => a.path.localeCompare(b.path));

  return {
    meta: {
      schemaVersion: SCHEMA_VERSION,
      hashAlgorithm: HASH_ALGO,
      generatedAt: new Date().toISOString(),
      generatedBy: "poly v0.1.0",
    },
    engines: [{ name: "node" }, { name: "python" }, { name: "rust" }, { name: "go" }],
    members: snapshots,
  };
}

/**
 * Serializes and writes poly.lock to the workspace root.
 */
export function writeCompositeLockfile(
  workspaceDir: string,
  lockfile?: CompositeLockfile,
): CompositeLockfile {
  const lock = lockfile ?? generateCompositeLockfile(workspaceDir);
  const lockfilePath = path.join(workspaceDir, "poly.lock");

  let output = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT DIRECTLY.\n";
  output += `# poly-lock-version = "${lock.meta.schemaVersion}"\n`;
  output += `# hash-algorithm = "${lock.meta.hashAlgorithm}"\n\n`;

  output += "[meta]\n";
  output += `schema_version = ${lock.meta.schemaVersion}\n`;
  output += `hash_algorithm = "${lock.meta.hashAlgorithm}"\n`;
  output += `generated_at = "${lock.meta.generatedAt}"\n`;
  output += `generated_by = "${lock.meta.generatedBy}"\n\n`;

  for (const m of lock.members) {
    output += "[[member]]\n";
    output += `path = "${m.path}"\n`;
    output += `ecosystem = "${m.ecosystem}"\n`;
    output += `manifest = "${m.manifest}"\n`;
    output += `manifest_hash = "${m.manifestHash}"\n`;
    if (m.lockfile) {
      output += `lockfile = "${m.lockfile}"\n`;
      output += `lockfile_hash = "${m.lockfileHash ?? ""}"\n`;
    }
    output += "dependencies = [\n";
    for (const dep of m.directDependencies) {
      output += `  "${dep}",\n`;
    }
    output += "]\n\n";
  }

  fs.writeFileSync(lockfilePath, output, "utf-8");
  return lock;
}

/**
 * Reads and parses an existing poly.lock file.
 */
export function readCompositeLockfile(workspaceDir: string): CompositeLockfile | undefined {
  const lockfilePath = path.join(workspaceDir, "poly.lock");
  if (!fs.existsSync(lockfilePath)) {
    return undefined;
  }

  const content = fs.readFileSync(lockfilePath, "utf-8");
  const lines = content.split("\n");

  const lock: CompositeLockfile = {
    meta: {
      schemaVersion: SCHEMA_VERSION,
      hashAlgorithm: HASH_ALGO,
      generatedAt: "",
      generatedBy: "",
    },
    engines: [],
    members: [],
  };

  let currentMember: Partial<MemberLockSnapshot> | undefined;
  let inDeps = false;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    if (line === "[[member]]") {
      if (currentMember?.path) {
        lock.members.push(currentMember as MemberLockSnapshot);
      }
      currentMember = { directDependencies: [] };
      inDeps = false;
      continue;
    }

    if (line.startsWith("dependencies = [")) {
      inDeps = true;
      continue;
    }

    if (inDeps) {
      if (line.startsWith("]")) {
        inDeps = false;
        continue;
      }
      const dep = line.replace(/[",]/g, "").trim();
      if (dep && currentMember) {
        currentMember.directDependencies?.push(dep);
      }
      continue;
    }

    const eqIdx = line.indexOf("=");
    if (eqIdx === -1) continue;
    const key = line.substring(0, eqIdx).trim();
    const val = line
      .substring(eqIdx + 1)
      .trim()
      .replace(/["']/g, "");

    if (currentMember) {
      if (key === "path") currentMember.path = val;
      if (key === "ecosystem") currentMember.ecosystem = val as Ecosystem;
      if (key === "manifest") currentMember.manifest = val;
      if (key === "manifest_hash") currentMember.manifestHash = val;
      if (key === "lockfile") currentMember.lockfile = val;
      if (key === "lockfile_hash") currentMember.lockfileHash = val;
    } else {
      if (key === "generated_at") lock.meta.generatedAt = val;
      if (key === "generated_by") lock.meta.generatedBy = val;
    }
  }

  if (currentMember?.path) {
    lock.members.push(currentMember as MemberLockSnapshot);
  }

  return lock;
}

/**
 * Compares current workspace disk state against poly.lock to detect supply-chain drift.
 */
export function verifyCompositeLockfile(workspaceDir: string): DriftReport {
  const existingLock = readCompositeLockfile(workspaceDir);
  const issues: DriftIssue[] = [];

  if (!existingLock) {
    return {
      isDrifted: true,
      issues: [
        {
          memberPath: ".",
          file: "poly.lock",
          expectedHash: "EXISTS",
          actualHash: "MISSING",
          reason: "poly.lock does not exist. Run 'poly sync' to generate it.",
        },
      ],
    };
  }

  const currentSnapshot = generateCompositeLockfile(workspaceDir);
  const lockMap = new Map<string, MemberLockSnapshot>();
  for (const m of existingLock.members) {
    lockMap.set(m.path, m);
  }

  for (const current of currentSnapshot.members) {
    const locked = lockMap.get(current.path);
    if (!locked) {
      issues.push({
        memberPath: current.path,
        file: current.manifest,
        expectedHash: "UNTRACKED",
        actualHash: current.manifestHash,
        reason: `New member '${current.path}' found on disk but missing from poly.lock.`,
      });
      continue;
    }

    // Check manifest hash
    if (current.manifestHash !== locked.manifestHash) {
      issues.push({
        memberPath: current.path,
        file: current.manifest,
        expectedHash: locked.manifestHash,
        actualHash: current.manifestHash,
        reason: `Manifest '${current.manifest}' was modified out-of-band.`,
      });
    }

    // Check lockfile hash
    if (current.lockfile && current.lockfileHash !== (locked.lockfileHash ?? "")) {
      issues.push({
        memberPath: current.path,
        file: current.lockfile,
        expectedHash: locked.lockfileHash ?? "NONE",
        actualHash: current.lockfileHash ?? "NONE",
        reason: `Native lockfile '${current.lockfile}' was modified out-of-band.`,
      });
    }
  }

  // Check for deleted members
  for (const locked of existingLock.members) {
    if (!currentSnapshot.members.some((c) => c.path === locked.path)) {
      issues.push({
        memberPath: locked.path,
        file: locked.manifest,
        expectedHash: locked.manifestHash,
        actualHash: "MISSING",
        reason: `Member '${locked.path}' in poly.lock no longer exists on disk.`,
      });
    }
  }

  return {
    isDrifted: issues.length > 0,
    issues,
  };
}
