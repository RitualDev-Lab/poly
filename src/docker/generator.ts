import fs from "node:fs";
import path from "node:path";
import { detectContexts } from "../detector/tree-walker.js";
import { resolveWorkspaceMembers } from "../workspace/config.js";
import type { DockerGeneratorOptions, GeneratedDockerArtifacts } from "./types.js";

export class DockerGenerator {
  /**
   * Generates optimized production multi-stage Dockerfile, compose, and devcontainer files.
   */
  generate(options: DockerGeneratorOptions): GeneratedDockerArtifacts {
    const workspaceDir = path.resolve(options.workspaceDir);
    const targetDir = path.resolve(options.outputDir ?? workspaceDir);

    const members = resolveWorkspaceMembers(workspaceDir);
    const contexts = detectContexts(workspaceDir);

    const allEcosystems = new Set<string>();
    for (const m of members) allEcosystems.add(m.context.ecosystem);
    for (const c of contexts) allEcosystems.add(c.ecosystem);

    const hasNode = allEcosystems.has("npm");
    const hasPython = allEcosystems.has("pypi");
    const hasRust = allEcosystems.has("cargo");
    const hasGo = allEcosystems.has("go");

    const dockerfile = this.buildDockerfile({ hasNode, hasPython, hasRust, hasGo });
    const dockerCompose = this.buildDockerCompose(workspaceDir, members, {
      hasNode,
      hasPython,
      hasRust,
      hasGo,
    });
    const devcontainerJson = options.devcontainer
      ? this.buildDevcontainerJson({ hasNode, hasPython, hasRust, hasGo })
      : undefined;

    const createdFiles: string[] = [];

    if (!options.dryRun) {
      if (!fs.existsSync(targetDir)) {
        fs.mkdirSync(targetDir, { recursive: true });
      }

      const dockerfilePath = path.join(targetDir, "Dockerfile");
      fs.writeFileSync(dockerfilePath, dockerfile, "utf-8");
      createdFiles.push(dockerfilePath);

      const composePath = path.join(targetDir, "docker-compose.yml");
      fs.writeFileSync(composePath, dockerCompose, "utf-8");
      createdFiles.push(composePath);

      if (devcontainerJson) {
        const devcontainerDir = path.join(targetDir, ".devcontainer");
        if (!fs.existsSync(devcontainerDir)) {
          fs.mkdirSync(devcontainerDir, { recursive: true });
        }
        const devPath = path.join(devcontainerDir, "devcontainer.json");
        fs.writeFileSync(devPath, devcontainerJson, "utf-8");
        createdFiles.push(devPath);
      }
    }

    return {
      dockerfile,
      dockerCompose,
      devcontainerJson,
      createdFiles,
    };
  }

  private buildDockerfile(eco: {
    hasNode: boolean;
    hasPython: boolean;
    hasRust: boolean;
    hasGo: boolean;
  }): string {
    const sections: string[] = [];
    sections.push("# syntax=docker/dockerfile:1.4");
    sections.push("# Multi-Stage Production Dockerfile Generated by Poly");
    sections.push("# https://ritualdev.in/poly\n");

    // 1. Node Builder Stage
    if (eco.hasNode) {
      sections.push("FROM node:22-bookworm-slim AS node-builder");
      sections.push("WORKDIR /app");
      sections.push("RUN corepack enable || true");
      sections.push(
        "RUN --mount=type=cache,target=/root/.npm npm install -g @ritualdev-lab/poly@latest",
      );
      sections.push("COPY . .");
      sections.push("RUN poly install || true\n");
    }

    // 2. Python Builder Stage
    if (eco.hasPython) {
      sections.push("FROM python:3.12-slim AS python-builder");
      sections.push("WORKDIR /app");
      sections.push("COPY --from=ghcr.io/astral-sh/uv:latest /uv /bin/uv");
      sections.push("ENV UV_SYSTEM_PYTHON=1");
      sections.push("COPY . .");
      sections.push(
        "RUN --mount=type=cache,target=/root/.cache/uv if [ -f 'pyproject.toml' ]; then uv sync --frozen || uv pip install -e .; fi\n",
      );
    }

    // 3. Rust Builder Stage
    if (eco.hasRust) {
      sections.push("FROM rust:1.84-slim AS rust-builder");
      sections.push("WORKDIR /app");
      sections.push("COPY . .");
      sections.push(
        "RUN --mount=type=cache,target=/usr/local/cargo/registry cargo build --release || true\n",
      );
    }

    // 4. Go Builder Stage
    if (eco.hasGo) {
      sections.push("FROM golang:1.24-alpine AS go-builder");
      sections.push("WORKDIR /app");
      sections.push("COPY . .");
      sections.push(
        "RUN --mount=type=cache,target=/go/pkg/mod if [ -f 'go.mod' ]; then go build -o /app/bin/server ./...; fi\n",
      );
    }

    // Final Production Stage
    sections.push("FROM debian:bookworm-slim AS runner");
    sections.push("WORKDIR /app");
    sections.push("RUN apt-get update && apt-get install -y --no-install-recommends \\");
    sections.push("    ca-certificates curl \\");
    sections.push("    && rm -rf /var/lib/apt/lists/*");

    // Copy runtime artifacts
    if (eco.hasNode) {
      sections.push("COPY --from=node-builder /usr/local/bin /usr/local/bin");
      sections.push(
        "COPY --from=node-builder /usr/local/lib/node_modules /usr/local/lib/node_modules",
      );
      sections.push("COPY --from=node-builder /app /app");
    }
    if (eco.hasPython) {
      sections.push("COPY --from=python-builder /usr/local /usr/local");
      sections.push("COPY --from=python-builder /app /app");
    }
    if (eco.hasRust) {
      sections.push("COPY --from=rust-builder /app/target/release /app/bin");
    }
    if (eco.hasGo) {
      sections.push("COPY --from=go-builder /app/bin /app/bin");
    }

    sections.push("\n# Security: Run as non-root unprivileged container");
    sections.push("RUN useradd -m -u 10001 appuser && chown -R appuser:appuser /app");
    sections.push("USER appuser");
    sections.push("ENV NODE_ENV=production");
    sections.push('ENTRYPOINT ["poly"]');
    sections.push('CMD ["run", "start"]\n');

    return sections.join("\n");
  }

  private buildDockerCompose(
    workspaceDir: string,
    members: ReturnType<typeof resolveWorkspaceMembers>,
    _eco: { hasNode: boolean; hasPython: boolean; hasRust: boolean; hasGo: boolean },
  ): string {
    const lines: string[] = [];
    lines.push('version: "3.8"');
    lines.push("services:");

    if (members.length > 0) {
      let defaultPort = 3000;
      for (const m of members) {
        const rawName = path.basename(m.relativeDir);
        const serviceName =
          !rawName || rawName === "." ? path.basename(workspaceDir) || "app" : rawName;
        const workingDir = m.relativeDir === "." ? "/app" : `/app/${m.relativeDir}`;
        lines.push(`  ${serviceName}:`);
        lines.push("    build:");
        lines.push("      context: .");
        lines.push("      dockerfile: Dockerfile");
        lines.push(`    working_dir: ${workingDir}`);
        lines.push("    ports:");
        lines.push(`      - "${defaultPort}:${defaultPort}"`);
        lines.push("    volumes:");
        lines.push("      - .:/app");
        lines.push("    environment:");
        lines.push(`      - PORT=${defaultPort}`);
        lines.push("      - NODE_ENV=development");
        lines.push("    command: poly run dev");
        lines.push("");
        defaultPort += 1000;
      }
    } else {
      lines.push("  app:");
      lines.push("    build:");
      lines.push("      context: .");
      lines.push("      dockerfile: Dockerfile");
      lines.push("    ports:");
      lines.push('      - "3000:3000"');
      lines.push("    volumes:");
      lines.push("      - .:/app");
      lines.push("    command: poly run dev\n");
    }

    return lines.join("\n");
  }

  private buildDevcontainerJson(eco: {
    hasNode: boolean;
    hasPython: boolean;
    hasRust: boolean;
    hasGo: boolean;
  }): string {
    const features: Record<string, Record<string, string>> = {};

    if (eco.hasNode) {
      features["ghcr.io/devcontainers/features/node:1"] = { version: "22" };
    }
    if (eco.hasPython) {
      features["ghcr.io/devcontainers/features/python:1"] = { version: "3.12" };
    }
    if (eco.hasRust) {
      features["ghcr.io/devcontainers/features/rust:1"] = {};
    }
    if (eco.hasGo) {
      features["ghcr.io/devcontainers/features/go:1"] = {};
    }

    const extensions = ["biomejs.biome"];
    if (eco.hasPython) extensions.push("ms-python.python", "charliermarsh.ruff");
    if (eco.hasRust) extensions.push("rust-lang.rust-analyzer");
    if (eco.hasGo) extensions.push("golang.go");

    const devcontainer = {
      name: "Polyglot Monorepo Workspace (poly)",
      image: "mcr.microsoft.com/devcontainers/base:bookworm",
      features,
      customizations: {
        vscode: {
          extensions,
        },
      },
      postCreateCommand: "npm install -g @ritualdev-lab/poly@latest && poly install",
    };

    return `${JSON.stringify(devcontainer, null, 2)}\n`;
  }
}
